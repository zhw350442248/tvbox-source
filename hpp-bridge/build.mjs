#!/usr/bin/env node
/**
 * 把 hghub-plugins 的 HPP 插件 + runtime + worker 打包成单文件 Worker
 *
 *   node build.mjs
 *   WORKER_HOST=xxx.workers.dev node build.mjs      # 顺手生成 TVBox 配置
 *
 * 产出：
 *   dist/worker.js        粘到 CF Workers 直接 Deploy
 *   dist/tvbox-hpp.json   TVBox 用的 type:1 配置（api 指向 Worker）
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DIST = path.join(HERE, 'dist');
const WORKER_HOST = process.env.WORKER_HOST || 'YOUR-WORKER.workers.dev';

const HGHUB_REPO = process.env.HGHUB_REPO || 'CoderL98/hghub-plugins';
const HGHUB_TAG = process.env.HGHUB_TAG || 'main';
const CACHE = path.join(HERE, '.plugins-cache');
const BASES = [
  `https://raw.githubusercontent.com/${HGHUB_REPO}/${HGHUB_TAG}`,
  `https://cdn.jsdelivr.net/gh/${HGHUB_REPO}@${HGHUB_TAG}`,
  `https://gh-proxy.com/https://raw.githubusercontent.com/${HGHUB_REPO}/${HGHUB_TAG}`,
];

async function fetchFirst(p) {
  let lastErr;
  for (const b of BASES) {
    try {
      const r = await fetch(b + p);
      if (!r.ok) { lastErr = new Error('HTTP ' + r.status); continue; }
      return await r.text();
    } catch (e) { lastErr = e; }
  }
  throw lastErr || new Error('mirror failed');
}

// 插件来源：本地 ../hghub-plugins/plugins → .plugins-cache → 从 GitHub 拉
async function ensurePlugins() {
  const local = path.join(HERE, '..', 'hghub-plugins', 'plugins');
  if (fs.existsSync(local) && fs.readdirSync(local).some((f) => f.endsWith('.js'))) return local;
  if (fs.existsSync(CACHE) && fs.readdirSync(CACHE).some((f) => f.endsWith('.js'))) return CACHE;

  console.log('本地没有 hghub-plugins，从 GitHub 拉取到 .plugins-cache/ ...');
  fs.mkdirSync(CACHE, { recursive: true });
  const manifest = JSON.parse(await fetchFirst('/manifest.json'));
  const list = Array.isArray(manifest.plugins) ? manifest.plugins : [];
  if (!list.length) throw new Error('manifest 里没有 plugins');
  for (const p of list) {
    const file = /\.js$/.test(p.url) ? p.url : `plugins/${p.id}.js`;
    const name = file.split('/').pop();
    const src = await fetchFirst('/' + file.replace(/^\//, ''));
    fs.writeFileSync(path.join(CACHE, name), src, 'utf8');
    console.log('  +', name);
  }
  return CACHE;
}

const PLUGIN_DIR = await ensurePlugins();
fs.mkdirSync(DIST, { recursive: true });

/* ---------- 1. 收集插件 ---------- */
const files = fs.readdirSync(PLUGIN_DIR).filter((f) => f.endsWith('.js')).sort();
if (!files.length) {
  console.error('没找到插件：' + PLUGIN_DIR);
  process.exit(1);
}

const varName = (f) => '__p_' + f.replace(/\.js$/, '').replace(/[^a-zA-Z0-9_]/g, '_');

function toIife(src, id) {
  let s = src;
  s = s.replace(/export\s+default\s+function\s*\(/g, 'const __default = function (');
  s = s.replace(/export\s+default\s+/g, 'const __default = ');
  s = s.replace(/export\s+const\s+/g, 'const ');
  s = s.replace(/export\s+let\s+/g, 'let ');
  s = s.replace(/export\s+var\s+/g, 'var ');
  s = s.replace(/export\s*\{[^}]*\}\s*;?/g, '');
  if (!/const\s+__default\s*=/.test(s)) {
    throw new Error(id + ': 没找到 export default');
  }
  return `/* ===== ${id} ===== */\nconst ${varName(id)} = (function () {\n${s}\nreturn { meta: meta, factory: __default };\n})();\n`;
}

/* ---------- 2. runtime 转 IIFE ---------- */
const runtimeSrc = fs.readFileSync(path.join(HERE, 'runtime.js'), 'utf8');
const runtimeIife = `/* ===== runtime ===== */\nconst { createHg, PluginError, parseHtmlDoc } = (function () {\nconst module = { exports: {} };\nconst exports = module.exports;\n${runtimeSrc}\nreturn module.exports;\n})();\n`;

/* ---------- 3. 插件 IIFE ---------- */
const parts = files.map((f) => {
  const src = fs.readFileSync(path.join(PLUGIN_DIR, f), 'utf8');
  return toIife(src, f.replace(/\.js$/, ''));
});

/* ---------- 4. PLUGINS 表 ---------- */
const entries = files.map((f) => {
  const id = f.replace(/\.js$/, '');
  return `  '${id}': ${varName(id)}`;
});
const pluginTable = `const PLUGINS = {\n${entries.join(',\n')}\n};\n`;

/* ---------- 5. worker 主体（剥掉 import / export 前的准备） ---------- */
let workerSrc = fs.readFileSync(path.join(HERE, 'worker.js'), 'utf8');
workerSrc = workerSrc.replace(/^import\s+.*?;\s*$/gm, '');
workerSrc = workerSrc.replace(/export\s+default\s*\{\s*\n\s*async\s+fetch/, 'const __worker = {\n  async fetch');
workerSrc += '\nexport default __worker;\n';

/* ---------- 6. 拼装 ---------- */
const out = [
  '/* HPP -> CMS bridge for TVBox. generated by build.mjs */',
  runtimeIife,
  parts.join('\n'),
  pluginTable,
  workerSrc,
].join('\n');

const outFile = path.join(DIST, 'worker.js');
fs.writeFileSync(outFile, out, 'utf8');
// 同一份内容再存 .mjs，方便本地 serve.mjs 直接 import
fs.writeFileSync(path.join(DIST, 'worker.mjs'), out, 'utf8');

/* ---------- 7. 语法自检 ---------- */
const check = await import('node:module').then((m) => m).catch(() => null);
void check;

/* ---------- 8. TVBox 配置 ---------- */
const metas = files.map((f) => {
  const src = fs.readFileSync(path.join(PLUGIN_DIR, f), 'utf8');
  const head = src.slice(0, 6000);
  const pick = (re) => (head.match(re) || [])[1] || '';
  return {
    id: pick(/\bid:\s*'([^']+)'/),
    name: pick(/\bname:\s*'([^']+)'/),
    mature: /\bmature:\s*true\b/.test(head),
  };
}).filter((m) => m.id);

const sites = metas.map((m) => ({
  key: 'hpp_' + m.id,
  name: (m.mature ? '🔞' : '') + m.name,
  type: 1,
  api: `https://${WORKER_HOST}/api.php/provide/vod?p=${m.id}`,
  searchable: 1,
  quickSearch: 1,
  filterable: 0,
  ext: '',
  group: m.mature ? '🔞18+' : '影视',
}));

const adult = sites.filter((s) => s.group === '🔞18+');
const normal = sites.filter((s) => s.group !== '🔞18+');
const config = {
  spider: '',
  wallpaper: '',
  logo: '',
  sites: [...adult, ...normal],
  lives: [],
  rules: [],
  ads: ['mimg.0c1q0l.cn', 'www.163.com'],
  flags: ['youku', 'qq', 'iqiyi', 'qiyi', 'letv', 'sohu', 'mgtv', 'bilibili'],
  ijk: [{ group: '软解码', options: [{ category: 4, name: 'mediacodec', value: '1' }] }],
  doh: [{ name: 'AliDNS', url: 'https://dns.alidns.com/dns-query', ips: ['223.5.5.5', '223.6.6.6'] }],
};

fs.writeFileSync(path.join(DIST, 'tvbox-hpp.json'), JSON.stringify(config, null, 2), 'utf8');

const kb = (n) => (n / 1024).toFixed(1) + ' KB';
console.log(`插件 ${files.length} 个`);
console.log(`-> dist/worker.js      ${kb(fs.statSync(outFile).size)}`);
console.log(`-> dist/tvbox-hpp.json ${sites.length} 站（🔞${adult.length} / 影视${normal.length}）`);
console.log(`\nWorker host: ${WORKER_HOST}`);
console.log(`TVBox api 示例: https://${WORKER_HOST}/api.php/provide/vod?p=${metas[0] ? metas[0].id : 'hdmoli'}`);
